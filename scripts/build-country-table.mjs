// Usage: node countries.mjs <fastapply countries.ts> <scout countries.json> <out.ts>
import { readFileSync, writeFileSync } from "node:fs";
const [src, scoutJson, out] = process.argv.slice(2);
const text = readFileSync(src, "utf8");
const rows = [...text.matchAll(/\{\s*id:\s*"([A-Z]{2})",\s*value:\s*"(\+[0-9-]+)",\s*label:\s*"([^"]+)",?\s*\}/g)]
  .map((m) => ({ id: m[1], dial: m[2], name: m[3].replace(/\s*\(\+[0-9-]+\)$/, "") }));
// FastApply's backend folds "czech republic" to "Czechia" (COUNTRY_ALIASES), so store that.
for (const row of rows) if (row.name === "Czech Republic") row.name = "Czechia";
const names = new Set(rows.map((r) => r.name));
const scout = JSON.parse(readFileSync(scoutJson, "utf8"));
const simplify = (s) => s.replace(/^St\. /, "Saint ").replace(/ St\. /g, " Saint ").replace(/ & /g, " and ").replace(/\s*\([^)]*\)\s*/g, " ").replace(/\s+/g, " ").trim();
const manual = {
  "Congo - Brazzaville": "Congo", "Congo - Kinshasa": "Democratic Republic of the Congo", "Côte d’Ivoire": "Ivory Coast",
  "Hong Kong SAR China": "Hong Kong", "Macao SAR China": "Macau", "Palestinian Territories": "Palestine", "Türkiye": "Turkey",
  "Cocos (Keeling) Islands": "Cocos Islands", "St. Vincent & Grenadines": "Saint Vincent and the Grenadines",
};
const aliases = {};
const unmatched = [];
for (const name of scout) {
  if (names.has(name)) continue;
  const target = manual[name] ?? simplify(name);
  if (names.has(target)) aliases[name] = target; else unmatched.push(name);
}
const lines = [];
lines.push(`/**`);
lines.push(` * Countries as FastApply names them, with their phone calling codes.`);
lines.push(` *`);
lines.push(` * Copied from FastApply's web app (src/lib/constants/countries.ts, PHONE_COUNTRY_CODES) on`);
lines.push(` * 2026-10-10 so Scout stores the same country names and the same phone-code ids FastApply`);
lines.push(` * stores for its own users: \`phoneCountryCode\` is the ISO id ("US", "CA"), never "+1", which`);
lines.push(` * cannot tell the United States from Canada. "Czech Republic" is stored as "Czechia" because`);
lines.push(` * FastApply's API folds it to that. Generated by scripts/build-country-table.mjs from that file; rerun it`);
lines.push(` * rather than editing by hand.`);
lines.push(` */`);
lines.push(`export interface CountryRow { id: string; dial: string; name: string }`);
lines.push(``);
lines.push(`/** FastApply's order: by calling code, the main country of a shared code first (US before CA). */`);
lines.push(`export const COUNTRY_ROWS: readonly CountryRow[] = [`);
for (const r of rows) lines.push(`  { id: ${JSON.stringify(r.id)}, dial: ${JSON.stringify(r.dial)}, name: ${JSON.stringify(r.name)} },`);
lines.push(`];`);
lines.push(``);
lines.push(`/**`);
lines.push(` * Scout's earlier country spellings (public/data/countries.json, CLDR style) folded onto the`);
lines.push(` * names above, so a profile saved before this table reads as the same country.`);
lines.push(` */`);
lines.push(`export const SCOUT_COUNTRY_ALIASES: Record<string, string> = ${JSON.stringify(aliases, null, 2).replace(/\n/g, "\n")};`);
lines.push(``);
writeFileSync(out, lines.join("\n"));
console.log(`rows=${rows.length} aliases=${Object.keys(aliases).length} unmatched=${JSON.stringify(unmatched)}`);
